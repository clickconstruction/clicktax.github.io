#!/usr/bin/env python3
"""Pairs a form's 2025 widgets with the 2024 widgets at the same page position: python3 tools/pair-years.py <form> [--ts out.ts].
Prints every 2025 widget whose 2024 name differs (or is missing) and every unmatched 2024 widget."""
import json, sys
form = sys.argv[1]
strip = lambda n: n.replace("topmostSubform[0].", "")
load = lambda y: json.load(open(f"packages/forms/pdf/{y}/{form}.draft.json"))
a, b = load("2025"), load("2024")
used = set(); pairs = {}; same = 0
for it in a:
    best = None
    for j, o in enumerate(b):
        if j in used or o["page"] != it["page"] or o["type"] != it["type"]: continue
        d = abs(o["x"] - it["x"]) + abs(o["y"] - it["y"])
        if d < 6 and (best is None or d < best[0]): best = (d, j)
    n25 = strip(it["pdfField"])
    if best:
        used.add(best[1]); n24 = strip(b[best[1]]["pdfField"])
        if n24 == n25: same += 1
        else: pairs[n25] = n24
    else:
        print(f"ONLY-2025 p{it['page']} x{it['x']:<6g} y{it['y']:<6g} {n25:55} | {it['rowText'][:50]}")
for j, o in enumerate(b):
    if j not in used: print(f"ONLY-2024 p{o['page']} x{o['x']:<6g} y{o['y']:<6g} {strip(o['pdfField']):55} | {o['rowText'][:50]}")
print(f"same-name {same}, renamed {len(pairs)}")
if "--ts" in sys.argv:
    out = sys.argv[sys.argv.index("--ts") + 1]
    lines = ["// Generated by tools/pair-years.py: 2025 widget name -> 2024 widget name at the same position.", "export const NAMES_2024: Record<string, string> = {"]
    for k, v in pairs.items(): lines.append(f"  {json.dumps(k)}: {json.dumps(v)},")
    lines.append("};\n"); open(out, "w").write("\n".join(lines)); print("wrote", out)
