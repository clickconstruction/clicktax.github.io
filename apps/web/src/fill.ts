import { decodePayload, type RenderPayload, type RenderStatement } from "@clicktax/forms";
import { PDFDocument, PDFCheckBox, PDFTextField, StandardFonts, rgb } from "pdf-lib";

const status = document.getElementById("status")!;
const out = document.getElementById("out")!;

const TITLES: Record<string, string> = {
  f1040: "Form 1040",
  f1040s1: "Schedule 1",
  f1040s2: "Schedule 2",
  f1040sc: "Schedule C",
  f1040sse: "Schedule SE",
  f1040s8: "Schedule 8812",
};
const titleOf = (f: { form: string; title?: string }) => f.title ?? TITLES[f.form] ?? f.form;

function esc(s: string): string {
  return s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);
}

async function fillOne(year: number, form: string, fields: Record<string, string | boolean>): Promise<{ blob: Blob; errors: string[] }> {
  const res = await fetch(`/forms/${year}/${form}.pdf`);
  if (!res.ok) throw new Error(`Could not load the blank ${TITLES[form] ?? form} for ${year}`);
  const pdf = await PDFDocument.load(await res.arrayBuffer(), { ignoreEncryption: true });
  const acro = pdf.getForm();
  const errors: string[] = [];
  for (const [name, value] of Object.entries(fields)) {
    try {
      const f = acro.getField(name);
      if (f instanceof PDFTextField) {
        f.setText(typeof value === "boolean" ? (value ? "X" : "") : value);
      } else if (f instanceof PDFCheckBox) {
        if (value === true || value === "X" || value === "true") f.check();
        else f.uncheck();
      } else {
        errors.push(`${name}: unsupported field type`);
      }
    } catch (e) {
      errors.push(`${name}: ${(e as Error).message}`);
    }
  }
  acro.updateFieldAppearances();
  const bytes = await pdf.save();
  return { blob: new Blob([bytes as BlobPart], { type: "application/pdf" }), errors };
}

/** Lays a statement out on Letter pages: title, header lines, a table with wrapped notes. */
async function renderStatement(year: number, st: RenderStatement): Promise<Blob> {
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const W = 612, H = 792, M = 54, LINE = 13;
  let page = pdf.addPage([W, H]);
  let y = H - M;
  const footer = () => page.drawText(`Generated by ClickTax (clicktax.org) in your browser from figures you supplied. Verify every amount. ${st.title} (${year})`, { x: M, y: 30, size: 7, font, color: rgb(0.4, 0.4, 0.4) });
  const ensure = (needed: number) => { if (y - needed < M + 20) { footer(); page = pdf.addPage([W, H]); y = H - M; } };
  const fit = (text: string, width: number, f = font, size = 9): string => {
    if (f.widthOfTextAtSize(text, size) <= width) return text;
    let t = text;
    while (t.length > 1 && f.widthOfTextAtSize(t + "…", size) > width) t = t.slice(0, -1);
    return t + "…";
  };
  const wrap = (text: string, width: number, f = font, size = 9): string[] => {
    const words = text.split(/\s+/);
    const lines: string[] = [];
    let cur = "";
    for (const w of words) {
      const next = cur ? `${cur} ${w}` : w;
      if (f.widthOfTextAtSize(next, size) > width && cur) { lines.push(cur); cur = w; } else cur = next;
    }
    if (cur) lines.push(cur);
    return lines;
  };
  const avail = W - 2 * M;
  for (const l of wrap(`${st.title} (${year})`, avail, bold, 13)) { ensure(LINE + 4); page.drawText(l, { x: M, y, size: 13, font: bold }); y -= 17; }
  for (const h of st.header ?? []) { ensure(LINE); page.drawText(fit(h, avail, font, 10), { x: M, y, size: 10, font }); y -= LINE; }
  y -= 6;
  const cols = st.columns ?? [];
  const nCols = Math.max(cols.length, ...(st.rows ?? []).map((r) => r.length));
  if (nCols) {
    const w0 = nCols > 1 ? avail * 0.38 : avail;
    const wi = nCols > 1 ? (avail - w0) / (nCols - 1) : 0;
    const xOf = (i: number) => (i === 0 ? M : M + w0 + wi * (i - 1));
    const wOf = (i: number) => (i === 0 ? w0 : wi);
    const align = st.align ?? Array.from({ length: nCols }, (_, i) => (i === 0 ? "l" : "r"));
    const drawRow = (cells: string[], f: typeof font, size: number) => {
      const wrapped = cells.map((c, i) => wrap(c ?? "", wOf(i) - 6, f, size));
      const lines = Math.max(1, ...wrapped.map((w) => w.length));
      ensure(lines * (size + 3) + 2);
      for (let li = 0; li < lines; li++) {
        wrapped.forEach((w, i) => {
          const t = w[li];
          if (!t) return;
          const tw = f.widthOfTextAtSize(t, size);
          const x = align[i] === "r" ? xOf(i) + wOf(i) - tw - 3 : xOf(i) + (i === 0 ? 0 : 3);
          page.drawText(t, { x, y, size, font: f });
        });
        y -= size + 3;
      }
      y -= 2;
    };
    if (cols.length) {
      drawRow(cols, bold, 8.5);
      page.drawLine({ start: { x: M, y: y + 6 }, end: { x: W - M, y: y + 6 }, thickness: 0.6, color: rgb(0.3, 0.3, 0.3) });
      y -= 2;
    }
    for (const r of st.rows ?? []) drawRow(r, font, 9);
  }
  y -= 8;
  for (const note of st.notes ?? []) {
    for (const l of wrap(note, avail, font, 8.5)) { ensure(LINE); page.drawText(l, { x: M, y, size: 8.5, font }); y -= LINE - 1; }
    y -= 5;
  }
  footer();
  const bytes = await pdf.save();
  return new Blob([bytes as BlobPart], { type: "application/pdf" });
}

async function main() {
  let payload: RenderPayload;
  try {
    if (!location.hash || location.hash.length < 4) {
      status.textContent = "This page renders forms from a ClickTax link. Ask your agent for one, or read about ClickTax on the home page.";
      return;
    }
    payload = await decodePayload(location.hash);
  } catch (e) {
    status.innerHTML = `<span class="err">That link could not be read: ${esc((e as Error).message)}</span>`;
    return;
  }
  if (payload.sample) {
    const b = document.createElement("div");
    b.className = "banner sample";
    b.textContent = "Sample data. These figures are invented for testing; nothing here is yours.";
    status.before(b);
  }
  status.textContent = `Filling ${payload.forms.length} form${payload.forms.length === 1 ? "" : "s"} for tax year ${payload.year} in your browser…`;
  const blobs: Array<{ name: string; url: string }> = [];
  for (const f of payload.forms) {
    const card = document.createElement("section");
    card.className = "card";
    const title = `${titleOf(f)} (${payload.year})`;
    card.innerHTML = `<h3>${esc(title)}</h3><p class="muted">Filling…</p>`;
    out.appendChild(card);
    try {
      const { blob, errors } = await fillOne(payload.year, f.form, f.fields);
      const url = URL.createObjectURL(blob);
      const fileName = `${payload.year}-${f.form}.pdf`;
      blobs.push({ name: fileName, url });
      const summary = (f.summary ?? [])
        .map((s) => `<tr><td class="muted">${esc(s.line ?? "")}</td><td>${esc(s.label)}</td><td class="num">${esc(s.value)}</td></tr>`)
        .join("");
      const comps = (f.notes?.computations ?? [])
        .map((c) => `<tr><td class="muted">${esc(c.line ?? "")}</td><td>${esc(c.label)}<br><span class="muted">${esc(c.formula)}</span></td><td class="num">${esc(typeof c.value === "number" ? c.value.toLocaleString("en-US") : String(c.value))}</td></tr>`)
        .join("");
      const warns = (f.notes?.warnings ?? []).map((w) => `<li>${esc(w)}</li>`).join("");
      const total = Object.keys(f.fields).length;
      const placedLine = errors.length ? `<p class="err">${total - errors.length} of ${total} fields placed. Could not place: ${esc(errors.slice(0, 5).join("; "))}</p>` : `<p class="ok">All ${total} fields placed on the official PDF.</p>`;
      card.innerHTML = `
        <h3>${esc(title)}</h3>
        <div class="row">
          <a class="btn" href="${url}" download="${fileName}">Download ${esc(titleOf(f))}</a>
          <a class="btn secondary" href="${url}" target="_blank" rel="noopener">Open in a new tab</a>
        </div>
        ${placedLine}
        <object class="preview" data="${url}" type="application/pdf"><p>Your browser cannot preview PDFs inline; use the download button.</p></object>
        ${comps ? `<details open><summary>How each line was computed</summary><table><tbody>${comps}</tbody></table></details>` : ""}
        ${warns ? `<details open><summary>Warnings (${(f.notes?.warnings ?? []).length})</summary><ul>${warns}</ul></details>` : ""}
        ${summary ? `<details><summary>Values placed on this form</summary><table><tbody>${summary}</tbody></table></details>` : ""}
      `;
    } catch (e) {
      card.innerHTML = `<h3>${esc(title)}</h3><p class="err">${esc((e as Error).message)}</p>`;
    }
  }
  for (const st of payload.statements ?? []) {
    const card = document.createElement("section");
    card.className = "card";
    const title = `${st.title} (${payload.year})`;
    card.innerHTML = `<h3>${esc(title)}</h3><p class="muted">Laying out…</p>`;
    out.appendChild(card);
    try {
      const blob = await renderStatement(payload.year, st);
      const url = URL.createObjectURL(blob);
      const fileName = `${payload.year}-statement-${st.id}.pdf`;
      blobs.push({ name: fileName, url });
      const table = st.columns?.length || st.rows?.length ? `<table>${st.columns?.length ? `<thead><tr>${st.columns.map((c) => `<th>${esc(c)}</th>`).join("")}</tr></thead>` : ""}<tbody>${(st.rows ?? []).map((r) => `<tr>${r.map((c, i) => `<td class="${i ? "num" : ""}">${esc(c)}</td>`).join("")}</tr>`).join("")}</tbody></table>` : "";
      card.innerHTML = `
        <h3>${esc(title)}</h3>
        <div class="row">
          <a class="btn" href="${url}" download="${fileName}">Download statement</a>
          <a class="btn secondary" href="${url}" target="_blank" rel="noopener">Open in a new tab</a>
        </div>
        <p class="ok">Supporting statement laid out in your browser; it is not an IRS form.</p>
        <object class="preview" data="${url}" type="application/pdf"><p>Your browser cannot preview PDFs inline; use the download button.</p></object>
        ${table ? `<details open><summary>Statement contents</summary>${table}</details>` : ""}
      `;
    } catch (e) {
      card.innerHTML = `<h3>${esc(title)}</h3><p class="err">${esc((e as Error).message)}</p>`;
    }
  }
  const nItems = payload.forms.length + (payload.statements?.length ?? 0);
  status.innerHTML = `${payload.title ? `<strong>${esc(payload.title)}</strong>. ` : ""}Done: ${nItems} document${nItems === 1 ? "" : "s"}. Review every line against the IRS instructions before you sign.`;
  if (blobs.length > 1) {
    const all = document.createElement("div");
    all.className = "row";
    all.innerHTML = `<button class="btn" id="dl-all">Download all ${blobs.length} PDFs</button>`;
    out.prepend(all);
    document.getElementById("dl-all")!.addEventListener("click", () => {
      for (const b of blobs) {
        const a = document.createElement("a");
        a.href = b.url;
        a.download = b.name;
        a.click();
      }
    });
  }
}

main();
